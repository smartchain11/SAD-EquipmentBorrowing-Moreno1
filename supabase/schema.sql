-- ---------- PROFILES / ROLES (Borrower, Officer, Administrator) ----------
CREATE TABLE IF NOT EXISTS public.profiles (
  id         UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role       TEXT NOT NULL DEFAULT 'borrower'
             CHECK (role IN ('borrower', 'officer', 'administrator')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Upgrade existing constraint if present
ALTER TABLE public.profiles DROP CONSTRAINT IF EXISTS profiles_role_check;
ALTER TABLE public.profiles ADD CONSTRAINT profiles_role_check CHECK (role IN ('borrower', 'officer', 'administrator'));

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "profiles_select_authed" ON public.profiles;
DROP POLICY IF EXISTS "profiles_insert_own"   ON public.profiles;
DROP POLICY IF EXISTS "profiles_update_own"   ON public.profiles;

CREATE POLICY "profiles_select_authed" ON public.profiles FOR SELECT TO authenticated USING (true);
CREATE POLICY "profiles_insert_own" ON public.profiles FOR INSERT TO authenticated WITH CHECK (auth.uid() = id);
CREATE POLICY "profiles_update_own" ON public.profiles FOR UPDATE TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);
GRANT SELECT, INSERT, UPDATE ON public.profiles TO authenticated;

-- ---------- TABLE 1: equipment ----------
CREATE TABLE IF NOT EXISTS public.equipment (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_name TEXT NOT NULL,
  category      TEXT NOT NULL,
  asset_code    TEXT UNIQUE NOT NULL,
  condition     TEXT NOT NULL DEFAULT 'Good'
                CHECK (condition IN ('Good', 'Fair', 'For Repair')),
  availability  TEXT NOT NULL DEFAULT 'Available'
                CHECK (availability IN ('Available', 'Borrowed')),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------- TABLE 2: borrow_transactions ----------
CREATE TABLE IF NOT EXISTS public.borrow_transactions (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id  BIGINT NOT NULL REFERENCES public.equipment(id) ON DELETE RESTRICT,
  borrower_name TEXT NOT NULL,
  borrower_type TEXT NOT NULL
                CHECK (borrower_type IN ('Student', 'Faculty', 'Staff')),
  department    TEXT NOT NULL,
  date_borrowed DATE NOT NULL DEFAULT CURRENT_DATE,
  due_date      DATE NOT NULL,
  date_returned DATE,
  claim_date    TIMESTAMPTZ,
  status        TEXT NOT NULL DEFAULT 'Pending'
                CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Borrowed', 'Returned', 'Overdue', 'Cancelled')),
  user_id       UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT due_date_not_before_borrow CHECK (due_date >= date_borrowed)
);

-- Allow new 7 statuses
ALTER TABLE public.borrow_transactions DROP CONSTRAINT IF EXISTS borrow_transactions_status_check;
ALTER TABLE public.borrow_transactions ADD CONSTRAINT borrow_transactions_status_check
  CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Borrowed', 'Returned', 'Overdue', 'Cancelled'));

CREATE INDEX IF NOT EXISTS idx_equipment_name   ON public.equipment (equipment_name);
CREATE INDEX IF NOT EXISTS idx_equipment_avail  ON public.equipment (availability);
CREATE INDEX IF NOT EXISTS idx_txn_borrower     ON public.borrow_transactions (borrower_name);
CREATE INDEX IF NOT EXISTS idx_txn_status       ON public.borrow_transactions (status);
CREATE INDEX IF NOT EXISTS idx_txn_equipment    ON public.borrow_transactions (equipment_id);

