-- ---------- HELPER: log_audit ----------
CREATE OR REPLACE FUNCTION public.log_audit(p_action TEXT, p_target_table TEXT, p_target_id BIGINT, p_details TEXT DEFAULT '') 
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  INSERT INTO public.audit_logs (action, target_table, target_id, details, performed_by)
  VALUES (p_action, p_target_table, p_target_id, p_details, auth.uid());
END;
$$;

-- ---------- BUSINESS LOGIC FUNCTIONS ----------

-- 1. Record Borrowing (Pending)
CREATE OR REPLACE FUNCTION public.record_borrow(
  p_equipment_id BIGINT, p_borrower_name TEXT, p_borrower_type TEXT, p_department TEXT, p_date_borrowed DATE, p_due_date DATE
) RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE v_id BIGINT;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.equipment WHERE id = p_equipment_id AND availability = 'Available') THEN
    RAISE EXCEPTION 'BR-03: Only available equipment may be borrowed.';
  END IF;
  IF p_date_borrowed > p_due_date THEN
    RAISE EXCEPTION 'BR-05: Due date cannot be earlier than the borrowing date.';
  END IF;

  INSERT INTO public.borrow_transactions
    (equipment_id, borrower_name, borrower_type, department, date_borrowed, due_date, status, user_id)
  VALUES
    (p_equipment_id, p_borrower_name, p_borrower_type, p_department, p_date_borrowed, p_due_date, 'Pending', auth.uid())
  RETURNING id INTO v_id;

  PERFORM public.log_audit('SUBMIT', 'borrow_transactions', v_id, 'Request submitted for equipment ' || p_equipment_id);
  RETURN v_id;
END;
$$;

-- 2. Approve Borrow (Pending -> Approved)
CREATE OR REPLACE FUNCTION public.approve_borrow(p_txn_id BIGINT) RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role IN ('officer', 'administrator')) THEN
    RAISE EXCEPTION 'Only officers or admins can approve requests.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.borrow_transactions WHERE id = p_txn_id AND status = 'Pending') THEN
    RAISE EXCEPTION 'Only pending requests can be approved.';
  END IF;
  
  UPDATE public.borrow_transactions SET status = 'Approved' WHERE id = p_txn_id;
  PERFORM public.log_audit('APPROVE', 'borrow_transactions', p_txn_id, 'Request approved.');
END;
$$;

-- 3. Reject Borrow (Pending -> Rejected)
CREATE OR REPLACE FUNCTION public.reject_borrow(p_txn_id BIGINT) RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role IN ('officer', 'administrator')) THEN
    RAISE EXCEPTION 'Only officers or admins can reject requests.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.borrow_transactions WHERE id = p_txn_id AND status = 'Pending') THEN
    RAISE EXCEPTION 'Only pending requests can be rejected.';
  END IF;

  UPDATE public.borrow_transactions SET status = 'Rejected' WHERE id = p_txn_id;
  PERFORM public.log_audit('REJECT', 'borrow_transactions', p_txn_id, 'Request rejected.');
END;
$$;

-- 4. Cancel Request (Borrower: Pending -> Cancelled)
CREATE OR REPLACE FUNCTION public.cancel_borrow(p_txn_id BIGINT) RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE v_user UUID; v_status TEXT;
BEGIN
  SELECT user_id, status INTO v_user, v_status FROM public.borrow_transactions WHERE id = p_txn_id;
  IF v_user <> auth.uid() THEN RAISE EXCEPTION 'You can only cancel your own requests.'; END IF;
  IF v_status <> 'Pending' THEN RAISE EXCEPTION 'Only pending requests can be cancelled.'; END IF;

  UPDATE public.borrow_transactions SET status = 'Cancelled' WHERE id = p_txn_id;
  PERFORM public.log_audit('CANCEL', 'borrow_transactions', p_txn_id, 'Request cancelled by borrower.');
END;
$$;

-- 5. Claim Equipment (Approved -> Borrowed)
CREATE OR REPLACE FUNCTION public.claim_equipment(p_txn_id BIGINT) RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE v_equipment_id BIGINT;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role IN ('officer', 'administrator')) THEN
    RAISE EXCEPTION 'Only officers can mark equipment as claimed/borrowed.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.borrow_transactions WHERE id = p_txn_id AND status = 'Approved') THEN
    RAISE EXCEPTION 'Only approved requests can be claimed.';
  END IF;

  SELECT equipment_id INTO v_equipment_id FROM public.borrow_transactions WHERE id = p_txn_id;
  
  -- Prevent claiming if equipment is currently unavailable (e.g. someone else borrowed it)
  IF NOT EXISTS (SELECT 1 FROM public.equipment WHERE id = v_equipment_id AND availability = 'Available') THEN
    RAISE EXCEPTION 'Equipment is currently unavailable. Wait for return or reject this request.';
  END IF;

  UPDATE public.borrow_transactions SET status = 'Borrowed', claim_date = NOW() WHERE id = p_txn_id;
  UPDATE public.equipment SET availability = 'Borrowed' WHERE id = v_equipment_id;
  
  PERFORM public.log_audit('STATUS_CHANGE', 'borrow_transactions', p_txn_id, 'Equipment claimed by borrower.');
END;
$$;

-- 6. Return Equipment (Borrowed/Overdue -> Returned)
CREATE OR REPLACE FUNCTION public.return_equipment(p_txn_id BIGINT) RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE v_equipment_id BIGINT;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role IN ('officer', 'administrator')) THEN
    RAISE EXCEPTION 'Only officers can process returns.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.borrow_transactions WHERE id = p_txn_id AND status IN ('Borrowed', 'Overdue')) THEN
    RAISE EXCEPTION 'Only borrowed or overdue equipment can be returned.';
  END IF;

  SELECT equipment_id INTO v_equipment_id FROM public.borrow_transactions WHERE id = p_txn_id;

  UPDATE public.borrow_transactions SET status = 'Returned', date_returned = CURRENT_DATE WHERE id = p_txn_id;
  UPDATE public.equipment SET availability = 'Available' WHERE id = v_equipment_id;
  
  PERFORM public.log_audit('COMPLETE', 'borrow_transactions', p_txn_id, 'Equipment returned.');
END;
$$;

